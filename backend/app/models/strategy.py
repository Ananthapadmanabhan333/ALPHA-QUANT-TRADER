from datetime import datetime, timezone
from typing import Any, Dict, List
import uuid

from sqlalchemy import (
    DateTime,
    Float,
    Index,
    Integer,
    JSON,
    String,
)
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base


class StrategyExperiment(Base):
    """
    Auditable experiment record storing strategy configuration,
    dataset cryptographic fingerprint, feature definitions, and execution summary.
    """
    __tablename__ = "strategy_experiments"

    id: Mapped[str] = mapped_column(
        String(36),
        primary_key=True,
        default=lambda: str(uuid.uuid4()),
    )
    strategy_id: Mapped[str] = mapped_column(String(50), nullable=False, index=True)
    strategy_version: Mapped[str] = mapped_column(String(20), nullable=False)
    config_id: Mapped[str] = mapped_column(String(20), nullable=False, index=True)

    symbol: Mapped[str] = mapped_column(String(20), nullable=False, index=True)
    interval: Mapped[str] = mapped_column(String(10), nullable=False)

    time_range_start: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    time_range_end: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    candle_count: Mapped[int] = mapped_column(Integer, nullable=False)

    dataset_fingerprint: Mapped[str] = mapped_column(String(64), nullable=False, index=True)

    parameters: Mapped[Dict[str, Any]] = mapped_column(JSON, nullable=False)
    feature_definitions: Mapped[Dict[str, Any]] = mapped_column(JSON, nullable=False)
    signal_timestamps: Mapped[List[str]] = mapped_column(JSON, nullable=False)

    total_signals: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    buy_signals: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    sell_signals: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    hold_signals: Mapped[int] = mapped_column(Integer, nullable=False, default=0)

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=lambda: datetime.now(timezone.utc),
    )

    __table_args__ = (
        Index("ix_strategy_experiments_lookup", "strategy_id", "symbol", "created_at"),
    )

    def __repr__(self) -> str:
        return (
            f"<StrategyExperiment(id='{self.id}', strategy='{self.strategy_id}', "
            f"symbol='{self.symbol}', signals={self.total_signals})>"
        )


class StrategySignal(Base):
    """
    Persisted individual signal observation generated by a strategy experiment.
    Auditable and strictly non-executing.
    """
    __tablename__ = "strategy_signals"

    id: Mapped[str] = mapped_column(
        String(36),
        primary_key=True,
        default=lambda: str(uuid.uuid4()),
    )
    experiment_id: Mapped[str] = mapped_column(String(36), nullable=False, index=True)
    strategy_id: Mapped[str] = mapped_column(String(50), nullable=False, index=True)
    strategy_version: Mapped[str] = mapped_column(String(20), nullable=False)
    config_id: Mapped[str] = mapped_column(String(20), nullable=False)

    decision_timestamp: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False, index=True)
    symbol: Mapped[str] = mapped_column(String(20), nullable=False, index=True)
    side: Mapped[str] = mapped_column(String(10), nullable=False)
    signal_score: Mapped[float] = mapped_column(Float, nullable=False)
    reference_price: Mapped[float] = mapped_column(Float, nullable=False)
    reason: Mapped[str] = mapped_column(String(255), nullable=False)

    relevant_features: Mapped[Dict[str, Any]] = mapped_column(JSON, nullable=False)

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=lambda: datetime.now(timezone.utc),
    )

    __table_args__ = (
        Index("ix_strategy_signals_exp_ts", "experiment_id", "decision_timestamp"),
        Index("ix_strategy_signals_query", "strategy_id", "symbol", "decision_timestamp"),
    )

    def __repr__(self) -> str:
        return (
            f"<StrategySignal(exp='{self.experiment_id}', ts='{self.decision_timestamp}', "
            f"side='{self.side}', score={self.signal_score:.2f})>"
        )
